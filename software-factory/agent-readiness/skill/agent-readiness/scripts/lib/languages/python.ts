// Poetry's venv goes in the project, where the test command finds it without Poetry.
export const POETRY_ENV = "POETRY_VIRTUALENVS_IN_PROJECT=true";

export function pyproject(dir: string): string {
  return exists(join(dir, "pyproject.toml")) ? readText(join(dir, "pyproject.toml")) : "";
}

export const UV_WORKSPACE = /^\[tool\.uv\.workspace\]/m;

// The folders a root pyproject.toml's [tool.uv.workspace] lists, less its excludes, each with its
// own pyproject.toml. They share the root's uv.lock and .venv.
export function uvWorkspaceMembers(tree: string): string[] {
  const section = pyproject(tree).match(/^\[tool\.uv\.workspace\][^\n]*\n([\s\S]*?)(?=^\[|(?![\s\S]))/m)?.[1];
  if (section === undefined) return [];
  const list = (key: string) => [...(section.match(new RegExp(`^${key}\\s*=\\s*\\[([\\s\\S]*?)\\]`, "m"))?.[1] ?? "").matchAll(/["']([^"']+)["']/g)].map((m) => m[1]);
  return workspaceDirs(tree, [...list("members"), ...list("exclude").map((p) => `!${p}`)], (d) => d !== "." && exists(join(tree, d, "pyproject.toml")));
}

// PEP 735 groups that hold a test runner. uv installs the dev group by default; a separate test
// group has to be asked for, and only where some project in the lock defines it.
const TEST_GROUP = /^(test|tests|testing)$/;

export function testGroups(tree: string, dirs: string[]): string[] {
  const groups = new Set<string>();
  for (const d of dirs) {
    const section = pyproject(join(tree, d)).match(/^\[dependency-groups\][^\n]*\n([\s\S]*?)(?=^\[|(?![\s\S]))/m)?.[1] ?? "";
    for (const m of section.matchAll(/^([\w.-]+)\s*=/gm)) if (TEST_GROUP.test(m[1])) groups.add(m[1]);
  }
  return [...groups].sort();
}

// The Poetry that wrote poetry.lock, from its header, so the install reads the lock the same way.
export function poetryVersion(dir: string): string | null {
  const f = join(dir, "poetry.lock");
  return exists(f) ? (readText(f).match(/@generated by Poetry (\d+\.\d+\.\d+)/)?.[1] ?? null) : null;
}

export const PY_LOCKFILES = ["uv.lock", "poetry.lock", "Pipfile.lock", "pdm.lock"];

const NO_LOCKFILE = "no lockfile is committed";

const TOX_CONFIG = (dir: string) => exists(join(dir, "tox.ini")) || exists(join(dir, "tox.toml")) || /^\[tool\.tox\]/m.test(pyproject(dir));

// The extras of [project.optional-dependencies] that declare pytest, so the install has the runner.
export function testExtras(dir: string): string[] {
  const section = pyproject(dir).match(/^\[project\.optional-dependencies\][^\n]*\n([\s\S]*?)(?=^\[|(?![\s\S]))/m)?.[1] ?? "";
  return [...section.matchAll(/^([\w.-]+)\s*=\s*\[([\s\S]*?)\]/gm)].filter((m) => /["']pytest\b/.test(m[2])).map((m) => m[1]).sort();
}

// tox runs the tests when the repo configures it and declares pytest nowhere else.
export function toxRuns(dir: string): boolean {
  const reqs = ["requirements.txt", "requirements-dev.txt", "pyproject.toml"].map((f) => (exists(join(dir, f)) ? readText(join(dir, f)) : "")).join("\n");
  return TOX_CONFIG(dir) && !/pytest/.test(reqs) && !exists(join(dir, "pytest.ini")) && !exists(join(dir, "conftest.py"));
}

const pip: Ecosystem = {
  id: "pip",
  label: "pip",
  lockfiles: [],
  rule: "`pip install` into a fresh virtualenv from a `requirements.txt` that pins every package with `==`, or from `pyproject.toml`",
  install: (tree, path) => {
    const dir = join(tree, path);
    // The test runner is often only in requirements-dev.txt.
    const dev = exists(join(dir, "requirements-dev.txt")) ? " -r requirements-dev.txt" : "";
    const extras = testExtras(dir);
    const project = extras.length ? ` -e '.[${extras.join(",")}]'` : " -e .";
    const req = exists(join(dir, "requirements.txt")) ? ` -r requirements.txt${dev}` : exists(join(dir, "pyproject.toml")) ? `${project}${dev}` : dev;
    const tox = toxRuns(dir) ? " tox" : "";
    const why = [extras.length ? `with the ${extras.join(" and ")} ${extras.length > 1 ? "extras" : "extra"}, which declare pytest` : "", tox ? "with tox, which runs the tests" : ""].filter(Boolean).join(", ");
    return { command: `python3 -m venv ${VENV} && ${VENV}/bin/pip install -q --disable-pip-version-check${req}${tox}`, reason: `virtualenv install from requirements${why ? `, ${why}` : ""}`, frozen: true };
  },
  unpinned: (tree, path) => {
    const req = join(tree, path, "requirements.txt");
    const lines = exists(req) ? readText(req).split("\n").map((l) => l.trim()).filter((l) => l && !l.startsWith("#") && !l.startsWith("-")) : [];
    const loose = lines.filter((l) => !l.includes("=="));
    if (lines.length === 0 && !exists(join(tree, path, "pyproject.toml"))) return "no requirements file or lockfile";
    if (loose.length > 0) return `requirements.txt doesn't pin exact versions for ${loose.length} of ${lines.length} packages`;
    return null;
  },
};

const uv: Ecosystem = {
  id: "uv",
  label: "uv",
  lockfiles: ["uv.lock"],
  rule: "`uv sync --frozen` from a committed `uv.lock`, every workspace member with the dev group and any test group",
  install: (tree, path) => {
    const dir = join(tree, path);
    const members = uvWorkspaceMembers(dir);
    const names = testGroups(dir, [".", ...members]);
    const groups = names.map((g) => ` --group ${g}`).join("");
    const all = members.length ? " --all-packages" : "";
    const what = members.length ? "every workspace member from the root uv.lock" : "uv.lock";
    const withGroups = names.length ? `, with the dev group and the ${names.join(" and ")} ${names.length > 1 ? "groups" : "group"}` : "";
    return exists(join(dir, "uv.lock"))
      ? { command: `uv sync --frozen${all}${groups}`, reason: `frozen install of ${what}${withGroups}`, frozen: true }
      : { command: `uv sync${all}${groups}`, reason: "no uv.lock, so the install can't be frozen", frozen: false };
  },
  unpinned: (tree, path) => (exists(join(tree, path, "uv.lock")) ? null : NO_LOCKFILE),
};

const poetry: Ecosystem = {
  id: "poetry",
  label: "Poetry",
  lockfiles: ["poetry.lock"],
  rule: "`poetry sync` (`poetry install --sync` before Poetry 2) from a committed `poetry.lock`, with the Poetry that wrote it",
  install: (tree, path) => {
    const dir = join(tree, path);
    if (!exists(join(dir, "poetry.lock"))) return { command: `${POETRY_ENV} poetry install --no-interaction -v`, reason: "no poetry.lock, so the install can't be frozen", frozen: false };
    // Both refuse a poetry.lock that no longer matches pyproject.toml; Poetry 2 renamed install --sync to sync.
    // -v prints the cause behind "All attempts to connect to pypi.org failed", such as a PermissionError.
    const major = Number(poetryVersion(dir)?.split(".")[0] ?? 2);
    return { command: `${POETRY_ENV} poetry ${major >= 2 ? "sync" : "install --sync"} --no-interaction -v`, reason: "frozen install from poetry.lock, with every non-optional group", frozen: true };
  },
  unpinned: (tree, path) => (exists(join(tree, path, "poetry.lock")) ? null : NO_LOCKFILE),
};

// uv sync and Poetry install into .venv; a uv workspace has one, at its root.
function pythonTest(tree: string, path: string, pm: Profile["packageManager"], workspaceMember: boolean): string | null {
  const dir = join(tree, path);
  const up = workspaceMember ? path.split("/").map(() => "..").join("/") + "/" : "";
  const python = pm === "uv" || pm === "poetry" ? `${up}.venv/bin/python` : `${VENV}/bin/python`;
  // A workspace member runs the root's pytest when the root declares it.
  const dirs = workspaceMember ? [dir, tree] : [dir];
  const reqs = dirs.flatMap((d) => ["requirements.txt", "requirements-dev.txt", "pyproject.toml"].map((f) => (exists(join(d, f)) ? readText(join(d, f)) : ""))).join("\n");
  if (PYTEST_DECLARED.test(reqs) || dirs.some((d) => exists(join(d, "pytest.ini")) || exists(join(d, "conftest.py")))) return `${python} -m pytest -q`;
  const project = djangoProject(dir);
  if (project === ".") return `${python} manage.py test`;
  if (project) return `${python} ${project}/manage.py test ${project}/`;
  if (pm === "pip" && toxRuns(dir)) return `${python} -m tox`;
  if (exists(join(dir, "tests"))) return `${python} -m unittest discover -s tests -t .`;
  return null;
}

// pytest as a dependency or its config table, not a word such as `.pytest_cache` in an exclude list.
const PYTEST_DECLARED = /(?<![\w.-])pytest(?:-[\w-]+)?(?!\w)|^\[tool\.pytest\b/m;

// The folder of a Django project's manage.py: the component's own, or the one folder below it that
// holds the project, as netbox/manage.py does. Django's own runner runs its tests.
function djangoProject(dir: string): string | null {
  if (exists(join(dir, "manage.py"))) return ".";
  const below = readdirSync(dir, { withFileTypes: true }).filter((d) => d.isDirectory() && !d.name.startsWith(".") && exists(join(dir, d.name, "manage.py")));
  return below.length === 1 ? below[0].name : null;
}

const DEFAULT_PYTHON = "3.12";

// The lowest Python a project's requires-python, or Poetry's python dependency, allows.
export function requiredPython(dir: string): string | null {
  const text = pyproject(dir);
  const poetry = text.match(/^\[tool\.poetry\.dependencies\][^\n]*\n([\s\S]*?)(?=^\[|(?![\s\S]))/m)?.[1] ?? "";
  const spec = text.match(/^requires-python\s*=\s*["']([^"']+)["']/m)?.[1] ?? poetry.match(/^python\s*=\s*["']([^"']+)["']/m)?.[1];
  const m = spec?.match(/(?:>=|\^|~=|==|~)\s*(\d+)\.(\d+)/);
  return m ? `${m[1]}.${m[2]}` : null;
}

const newer = (a: string, b: string) => {
  const [x, y] = [a, b].map((v) => v.split(".").map(Number));
  return x[0] !== y[0] ? x[0] > y[0] : x[1] > y[1];
};

// The default Python, or a newer one when a project needs it, so the image satisfies requires-python.
function pythonFor(dirs: string[]): string {
  return dirs.map(requiredPython).filter((v): v is string => v !== null).reduce((best, v) => (newer(v, best) ? v : best), DEFAULT_PYTHON);
}

function pythonImage(tree: string, dir: string, pm: Profile["packageManager"]): string {
  const file = [dir, "."].map((d) => join(tree, d, ".python-version")).find(exists);
  const pv = file ? readText(file).trim().match(/^(\d+\.\d+)/)?.[1] : null;
  const version = pv ?? pythonFor([join(tree, dir)]);
  return pm === "uv" ? `ghcr.io/astral-sh/uv:python${version}-trixie-slim` : `python:${version}-slim`;
}

const PY_MANAGERS = new Set<Profile["packageManager"]>(["pip", "uv", "poetry"]);

function pythonCommands(tree: string, c: Component, ctx: ContractContext): ContractCommand[] {
  const test = pythonTest(tree, c.path, c.packageManager ?? ctx.profile.packageManager, c.stack === "uv-workspace" && c.path !== "." && !c.packageManager);
  return test ? [{ id: `cmd-${c.id}-test`, kind: "test", component: c.id, cwd: c.path, command: test, source: c.manifest ?? "readiness", reason: "discovered test runner", timeoutSec: ctx.timeoutSec, tier: "convention", confidence: "derived" }] : [];
}

// pytest and unittest.
function pythonTestCounts(text: string): { passed: number; failed: number; total: number } | null {
  const num = (re: RegExp) => lastNumber(text, re);
  const pytest = [...text.matchAll(/(?:(\d+) failed, )?(\d+) passed(?:, \d+ \w+)* in [\d.]+s/g)].pop();
  if (pytest) return { passed: Number(pytest[2]), failed: Number(pytest[1] ?? 0), total: Number(pytest[2]) + Number(pytest[1] ?? 0) };
  const ran = num(/^Ran (\d+) tests? in /m);
  if (ran !== null) {
    const failed = (num(/FAILED \((?:failures=(\d+))/m) ?? 0) + (num(/FAILED \([^)]*errors=(\d+)/m) ?? 0);
    return { passed: ran - failed, failed, total: ran };
  }
  return null;
}

